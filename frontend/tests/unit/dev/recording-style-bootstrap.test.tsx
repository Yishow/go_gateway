import { act, fireEvent, screen, waitFor } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import type { Root } from 'react-dom/client';
let mounted: Root | undefined;
afterEach(async () => { await act(async () => mounted?.unmount()); document.body.innerHTML = ''; vi.restoreAllMocks(); vi.unstubAllGlobals(); });
it('keeps the real iframe bootstrap and all preview interactions free of persistent or network writes', async () => {
  const storage = vi.spyOn(Storage.prototype, 'setItem');
  const remove = vi.spyOn(Storage.prototype, 'removeItem');
  const clear = vi.spyOn(Storage.prototype, 'clear');
  const fetch = vi.fn(); vi.stubGlobal('fetch', fetch);
  const xhr = vi.spyOn(XMLHttpRequest.prototype, 'open');
  const { settingsAPI } = await import('@/services/datalink');
  const { studioV2WorkspaceWriteGroupsAPI } = await import('@/services/studioV2WorkspaceWriteGroups');
  const settings = vi.spyOn(settingsAPI, 'updateKey');
  const commands = (['create', 'update', 'apply', 'schemaApply', 'remove'] as const).map(key => vi.spyOn(studioV2WorkspaceWriteGroupsAPI, key));
  document.body.innerHTML = '<div id="root"></div>';
  await act(async () => { const entry = await import('@/dev/recording-style-entry'); mounted = await entry.previewReady; });
  await screen.findByTestId('recording-home');
  expect(storage.mock.calls).toEqual([]);
  fireEvent.change(screen.getByLabelText('Preview theme'), { target: { value: 'dark' } });
  fireEvent.change(screen.getByLabelText('Preview state'), { target: { value: 'error' } });
  fireEvent.change(screen.getByLabelText('Sample input'), { target: { value: 'sample' } });
  for (const button of screen.getByTestId('recording-home').querySelectorAll('button')) fireEvent.click(button);
  fireEvent.click(screen.getByRole('button', { name: 'Preview confirmation' }));
  fireEvent.click(await screen.findByTestId('group-delete-cancel'));
  fireEvent.click(screen.getByRole('button', { name: 'Preview confirmation' }));
  fireEvent.click(await screen.findByTestId('group-delete-confirm-button'));
  await waitFor(() => expect(screen.queryByRole('alertdialog')).not.toBeInTheDocument());
  expect(storage.mock.calls).toEqual([]); expect(remove).not.toHaveBeenCalled(); expect(clear).not.toHaveBeenCalled();
  expect(fetch).not.toHaveBeenCalled(); expect(xhr).not.toHaveBeenCalled(); expect(settings).not.toHaveBeenCalled();
  commands.forEach(command => expect(command).not.toHaveBeenCalled());
});
