func TestHandoffReclaimCompactsWithoutChangingViewOrInventingReplay(t *testing.T) {
	store, _ := seedPreparedHandoff(t)
	_, err := store.PrepareCutoverHandoffs(t.Context(), testKey, 0, 128)
	require.NoError(t, err)
	target, err := store.Restore(t.Context(), otherKey)
	require.NoError(t, err)
	original := target.Samples[0]
	beforeView := target.HandoffView
	removed, err := store.Reclaim(t.Context(), time.Hour)
	require.NoError(t, err)
	require.Zero(t, removed, "open target pins original bytes")
	require.Equal(t, 2, countRows(t, store.DB(), "wg_delivery_samples"))
	require.NoError(t, store.CommitClosure(t.Context(), otherKey, Closure{OwnershipView: target.OwnershipView, HandoffView: beforeView, Destination: testDestination, NextClose: at(30)}))
	_, err = store.Reclaim(t.Context(), time.Hour)
	require.NoError(t, err)
	require.Zero(t, countRows(t, store.DB(), "wg_delivery_samples"))
	require.Equal(t, 1, openCount(t, store.DB(), "wg_delivery_sample_handoffs", "state='finalized'"))
	after, err := store.Restore(t.Context(), otherKey)
	require.NoError(t, err)
	require.Equal(t, beforeView, after.HandoffView)
	require.Equal(t, target.OwnershipView, after.OwnershipView)
	recognized, err := store.RecognizeTransferredSample(t.Context(), otherKey, original)
	require.NoError(t, err)
	require.True(t, recognized.Found)
	require.True(t, recognized.Finalized)
	require.Nil(t, recognized.Sample)
	require.ErrorIs(t, store.AppendSample(t.Context(), otherKey, at(20), original), ErrOwnershipConflict)
	require.NoError(t, store.CommitClosure(t.Context(), otherKey, Closure{OwnershipView: target.OwnershipView, HandoffView: beforeView, Destination: testDestination, NextClose: at(40)}), "GC alone cannot stale an assembler")
}

func TestHandoffTransitiveReclaimReleasesOnlyAfterConsumedLeaf(t *testing.T) {
	store, seq := seedPreparedHandoff(t)
	db := store.DB()
	// Build a distinct future original before either transfer, preserving the
	// exact bytes subsequently copied along A -> B -> C.
	sample := sampleAt("future-accepted", ownershipMember, 45, 7)
	sample.ReceivedAt = at(21)
	payload, digest, err := encodeSample(sample)
	require.NoError(t, err)
	_, err = db.Exec("UPDATE wg_delivery_samples SET observed_at=?,bucket_start=?,payload=?,payload_digest=? WHERE seq=?", timestamp(sample.ObservedAt), timestamp(at(40)), string(payload), digest, seq)
	require.NoError(t, err)
	_, err = store.PrepareCutoverHandoffs(t.Context(), testKey, 0, 128)
	require.NoError(t, err)
	third := GroupKey{WorkspaceID: testKey.WorkspaceID, GroupID: "owner-C", GroupRevision: "rev-C"}
	require.NoError(t, store.SaveRuntimeVersion(t.Context(), third, handoffProofDescriptor(t, third, nil, true)))
	seedOwnershipCutover(t, db, "B-C", otherKey, third, at(40))
	_, err = store.PrepareCutoverHandoffs(t.Context(), otherKey, 0, 128)
	require.NoError(t, err)
	target, err := store.Restore(t.Context(), third)
	require.NoError(t, err)
	require.Len(t, target.Samples, 1)
	recognized, recognitionErr := store.RecognizeTransferredSample(t.Context(), otherKey, target.Samples[0])
	require.ErrorIs(t, recognitionErr, ErrOwnershipConflict, "a forwarded intermediate is no longer a replay consumer")
	require.Nil(t, recognized.Sample)
	_, err = store.PrepareCutoverHandoffs(t.Context(), testKey, 0, 128)
	require.NoError(t, err, "retry old transfer never creates shortcut A -> C")
	require.Equal(t, 3, countRows(t, db, "wg_delivery_samples"))
	require.Equal(t, 2, countRows(t, db, "wg_delivery_sample_handoffs"))
	_, err = store.Reclaim(t.Context(), time.Hour)
	require.NoError(t, err)
	require.Equal(t, 3, countRows(t, db, "wg_delivery_samples"))
	require.NoError(t, store.CommitClosure(t.Context(), third, Closure{OwnershipView: target.OwnershipView, HandoffView: target.HandoffView, Destination: testDestination, NextClose: at(50)}))
	_, err = store.Reclaim(t.Context(), time.Hour)
	require.NoError(t, err)
	require.Zero(t, countRows(t, db, "wg_delivery_samples"))
	require.Equal(t, 2, openCount(t, db, "wg_delivery_sample_handoffs", "state='finalized'"))
	after, err := store.Restore(t.Context(), third)
	require.NoError(t, err)
	require.Equal(t, target.HandoffView, after.HandoffView)
}

func TestHandoffTransitiveDistinctOriginsWithSameSampleID(t *testing.T) {
	store, seq := seedPreparedHandoff(t)
	db := store.DB()
	a := sampleAt("future-accepted", ownershipMember, 43, 7)
	a.ReceivedAt = at(21)
	payload, digest, err := encodeSample(a)
	require.NoError(t, err)
	_, err = db.Exec("UPDATE wg_delivery_samples SET observed_at=?,bucket_start=?,payload=?,payload_digest=? WHERE seq=?", timestamp(a.ObservedAt), timestamp(at(40)), string(payload), digest, seq)
	require.NoError(t, err)
	_, err = store.PrepareCutoverHandoffs(t.Context(), testKey, 0, 128)
	require.NoError(t, err)
	b := sampleAt(a.SampleID, ownershipMember, 45, 9)
	require.NoError(t, store.AppendSample(t.Context(), otherKey, at(40), b), "native B identity differs from transferred A identity")
	third := GroupKey{WorkspaceID: testKey.WorkspaceID, GroupID: "owner-C", GroupRevision: "rev-C"}
	require.NoError(t, store.SaveRuntimeVersion(t.Context(), third, handoffProofDescriptor(t, third, nil, true)))
	seedOwnershipCutover(t, db, "B-C", otherKey, third, at(40))
	batch, err := store.PrepareCutoverHandoffs(t.Context(), otherKey, 0, 128)
	require.NoError(t, err)
	require.Equal(t, 2, batch.Accepted)
	c, err := store.Restore(t.Context(), third)
	require.NoError(t, err)
	require.Len(t, c.Samples, 2)
	for _, sample := range c.Samples {
		require.True(t, c.AuthorizesHandoff(sample, sample.CounterProof), "both verified original identities retain private authorization")
	}
	require.Equal(t, c.Samples[0].SampleID, c.Samples[1].SampleID)
	require.NotEqual(t, c.Samples[0].ObservedAt, c.Samples[1].ObservedAt)
	require.NoError(t, store.CommitClosure(t.Context(), third, Closure{OwnershipView: c.OwnershipView, HandoffView: c.HandoffView, Destination: testDestination, NextClose: at(50)}))
	_, err = store.Reclaim(t.Context(), time.Hour)
	require.NoError(t, err)
	require.Zero(t, countRows(t, db, "wg_delivery_samples"))
}

func TestHandoffPendingTargetSuccessionPreservesStableIntent(t *testing.T) {
	store, seq := seedPreparedHandoff(t)
	db := store.DB()
	sample := sampleAt("future-accepted", ownershipMember, 45, 7)
	sample.ReceivedAt = at(21)
	payload, digest, err := encodeSample(sample)
	require.NoError(t, err)
	_, err = db.Exec("UPDATE wg_delivery_samples SET observed_at=?,bucket_start=?,payload=?,payload_digest=? WHERE seq=?", timestamp(sample.ObservedAt), timestamp(at(40)), string(payload), digest, seq)
	require.NoError(t, err)
	_, err = db.Exec("DELETE FROM wg_runtime_versions WHERE group_id=?", otherKey.GroupID)
	require.NoError(t, err)
	batch, err := store.PrepareCutoverHandoffs(t.Context(), testKey, 0, 128)
	require.ErrorIs(t, err, ErrOwnershipUnavailable)
	require.Equal(t, 1, batch.Pending)
	var originalIntent string
	require.NoError(t, db.QueryRow("SELECT transfer_id FROM wg_delivery_sample_handoffs").Scan(&originalIntent))
	third := GroupKey{WorkspaceID: testKey.WorkspaceID, GroupID: "successor-C", GroupRevision: "rev-C"}
	require.NoError(t, store.SaveRuntimeVersion(t.Context(), third, handoffProofDescriptor(t, third, nil, true)))
	seedOwnershipCutover(t, db, "B-C", otherKey, third, at(40))
	c, err := store.Restore(t.Context(), third)
	require.NoError(t, err)
	require.ErrorIs(t, store.CommitClosure(t.Context(), third, Closure{OwnershipView: c.OwnershipView, HandoffView: c.HandoffView, Destination: testDestination, NextClose: at(50)}), ErrOwnershipConflict, "pending ancestor must prevent an empty successor closing past its original")
	batch, err = store.PrepareCutoverHandoffs(t.Context(), testKey, 0, 128)
	require.ErrorIs(t, err, ErrOwnershipUnavailable, "retry retains original B obligation until its proof exists")
	require.Equal(t, 1, batch.Pending)
	require.Equal(t, 1, countRows(t, db, "wg_delivery_sample_handoffs"))
	_, err = store.Restore(t.Context(), testKey)
	require.NoError(t, err, "pending retry cannot poison the durable fanout")
	require.Equal(t, 1, openCount(t, db, "wg_delivery_sample_handoffs", "transfer_id='"+originalIntent+"'"))
	require.NoError(t, store.SaveRuntimeVersion(t.Context(), otherKey, handoffProofDescriptor(t, otherKey, nil, true)))
	_, err = store.PrepareCutoverHandoffs(t.Context(), testKey, 0, 128)
	require.NoError(t, err)
	b, err := store.Restore(t.Context(), otherKey)
	require.NoError(t, err)
	require.Len(t, b.Samples, 1)
	require.ErrorIs(t, store.CommitClosure(t.Context(), otherKey, Closure{OwnershipView: b.OwnershipView, HandoffView: b.HandoffView, Destination: testDestination, NextClose: at(50)}), ErrOwnershipConflict, "intermediate cannot consume the now C-owned original")
	_, err = store.PrepareCutoverHandoffs(t.Context(), otherKey, 0, 128)
	require.NoError(t, err)
	c, err = store.Restore(t.Context(), third)
	require.NoError(t, err)
	require.Len(t, c.Samples, 1)
	require.Equal(t, 1, openCount(t, db, "wg_delivery_sample_handoffs", "transfer_id='"+originalIntent+"' AND state='accepted'"))
	require.NoError(t, store.CommitClosure(t.Context(), third, Closure{OwnershipView: c.OwnershipView, HandoffView: c.HandoffView, Destination: testDestination, NextClose: at(50)}))
	_, err = store.Reclaim(t.Context(), time.Hour)
	require.NoError(t, err)
	require.Zero(t, countRows(t, db, "wg_delivery_samples"))
	require.Equal(t, 2, openCount(t, db, "wg_delivery_sample_handoffs", "state='finalized'"))
}
