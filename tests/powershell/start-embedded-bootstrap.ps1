# Dev bootstrap contract: only a missing/empty embedded index invokes --prepare-dev.
Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
$env:GATEWAY_START_PS1_LIBRARY_ONLY = "1"
. (Join-Path $repoRoot "start.ps1")
Remove-Item Env:\GATEWAY_START_PS1_LIBRARY_ONLY -ErrorAction SilentlyContinue

$testRoot = Join-Path ([System.IO.Path]::GetTempPath()) ("start-embedded-test-" + [System.IO.Path]::GetRandomFileName())
$staticRoot = Join-Path $testRoot "cmd/test_ui/static"
$indexPath = Join-Path $staticRoot "index.html"
$script:ROOT_DIR = $testRoot
$script:NodeCalls = @()
New-Item -ItemType Directory -Path $staticRoot -Force | Out-Null

function node {
    $script:NodeCalls += ,@($args)
    Set-Content -LiteralPath $indexPath -Value "generated by prepare-dev"
    $global:LASTEXITCODE = 0
}

$exitCode = 0
try {
    # A usable snapshot must bypass the bootstrap command.
    Set-Content -LiteralPath $indexPath -Value "existing snapshot"
    if (-not (Sync-EmbeddedFrontendIfRequested)) { throw "既有 embedded index 應直接通過" }
    if ($script:NodeCalls.Count -ne 0) { throw "既有 embedded index 不應呼叫 prepare-dev" }

    # A fresh clone has no index and must prepare it before Air starts.
    Remove-Item -LiteralPath $indexPath -Force
    if (-not (Sync-EmbeddedFrontendIfRequested)) { throw "缺少 embedded index 應完成 prepare-dev" }
    if ($script:NodeCalls.Count -ne 1) { throw "缺少 embedded index 應只呼叫一次 prepare-dev" }
    if ($script:NodeCalls[0] -notcontains "--prepare-dev") { throw "prepare-dev 參數遺失" }
    if ((Get-Item -LiteralPath $indexPath).Length -eq 0) { throw "prepare-dev 應產生非空 index" }

    # An empty index is also unusable and must be rebuilt.
    [System.IO.File]::WriteAllText($indexPath, "")
    if (-not (Sync-EmbeddedFrontendIfRequested)) { throw "空 embedded index 應完成 prepare-dev" }
    if ($script:NodeCalls.Count -ne 2) { throw "空 embedded index 應再次呼叫 prepare-dev" }
    Write-Host "PASS: start-embedded-bootstrap.ps1"
}
catch {
    Write-Host "FAIL: $($_.Exception.Message)" -ForegroundColor Red
    $exitCode = 1
}
finally { Remove-Item -LiteralPath $testRoot -Recurse -Force -ErrorAction SilentlyContinue }
exit $exitCode
